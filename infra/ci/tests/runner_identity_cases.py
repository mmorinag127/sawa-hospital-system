RUN_IDENTITIES = (
    'INVOCATION_ID', 'JOURNAL_STREAM', 'SYSTEMD_EXEC_PID',
    'MEMORY_PRESSURE_WATCH', 'MEMORY_PRESSURE_WRITE', 'NODE_TEST_WORKER_ID',
    'CODEX_TOOL_CALL_ID', 'SAWA_LOCAL_RUN_ID', 'SAWA_LOCAL_EVIDENCE_DIR',
    'SAWA_LOCAL_TEST_MODE', 'SAWA_LOCAL_SOURCE_SHA',
    'SAWA_LOCAL_TEST_IMAGE_BACKEND', 'SAWA_LOCAL_TEST_IMAGE_OCR_PIPELINE',
    'SAWA_LOCAL_TEST_IMAGE_AGENT_RUNTIME', 'SAWA_LOCAL_FUTURE_COMPONENT_ID',
    'PG_BIN', 'REFRESH_TEST_PG_BIN',
)


def runner_values(second=False):
    values = {key: 'second-run' if second else 'first-run' for key in RUN_IDENTITIES}
    values['SAWA_LOCAL_SOURCE_SHA'] = ('b' if second else 'a') * 40
    return values
